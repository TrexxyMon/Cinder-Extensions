// Cinder installs a single standalone file per extension.
const fs = require('node:fs');
const path = require('node:path');
const createPlayerSource = require('./wordpress-player-source.cjs');
const root = path.join(__dirname, '..');
const catalog = JSON.parse(fs.readFileSync(path.join(root, 'repo.json'), 'utf8')).extensions;
const layouts = {
  fulllengthaudiobooks: {
    body: '.entry.clearfix',
    cover: '.wp-caption img',
    categories: '.postinfo a[rel~="category"]',
    description: '.collapseomatic_content p',
  },
  bookaudiobooks: {
    body: '.entry-content',
    cover: '.image-hover-wrapper img, .entry-content .wp-caption img, .entry-content img.wp-image',
    categories: '.cat-links a',
    description: 'p',
  },
};

for (const [id, layout] of Object.entries(layouts)) {
  const entry = catalog.find(row => row.id === id);
  const { name, version, capabilities, description, browser } = entry;
  const config = { id, name, description, capabilities, browser, layout };
  const output = [
    '// Generated by scripts/build-player-sources.cjs from repo.json and the WordPress player adapter.',
    createPlayerSource.toString(),
    'const version = ' + JSON.stringify(version) + ';',
    '__cinderExport = createPlayerSource(' + JSON.stringify(config, null, 2) + ', version);',
    '',
  ].join('\n').replace(/\r\n/g, '\n');
  const target = path.join(root, id + '.js');
  if (process.argv.includes('--check')) {
    if (fs.readFileSync(target, 'utf8').replace(/\r\n/g, '\n') !== output) throw new Error('Regenerate ' + id + '.js');
  } else {
    fs.writeFileSync(target, output);
  }
}
